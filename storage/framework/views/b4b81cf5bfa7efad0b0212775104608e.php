    var prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    // Animate counters in the trust bar
    var counters = document.querySelectorAll('.jb-counter');
    counters.forEach(function (counter) {
        var targetValue = parseInt(counter.getAttribute('data-target'), 10);
        var suffix = counter.getAttribute('data-suffix') || '';
        
        if (isNaN(targetValue)) return;
        
        // Handle reduced motion
        if (prefersReduced) {
            counter.innerHTML = targetValue.toLocaleString('en-US') + suffix;
            return;
        }

        var duration = 1800;
        var startTime = null;

        function updateCounter(currentTime) {
            if (!startTime) startTime = currentTime;
            var elapsed = currentTime - startTime;
            var progress = Math.min(elapsed / duration, 1);
            
            // Ease out cubic
            var easeProgress = 1 - Math.pow(1 - progress, 3);
            
            var currentValue = Math.floor(easeProgress * targetValue);

            counter.innerHTML = currentValue.toLocaleString('en-US') + suffix;

            if (progress < 1) {
                requestAnimationFrame(updateCounter);
            } else {
                counter.innerHTML = targetValue.toLocaleString('en-US') + suffix;
            }
        }

        counter.innerHTML = '0' + suffix;
        requestAnimationFrame(updateCounter);
    });

    // Fade Up Entrance Animation
    const page = document.querySelector('.jb-home');
    if (page && "IntersectionObserver" in window && !prefersReduced) {
        const sections = page.querySelectorAll('.reveal-section');
        const observer = new IntersectionObserver(
            (entries, observer) => {
                entries.forEach((entry) => {
                    if (entry.isIntersecting) {
                        entry.target.classList.add('is-visible');
                        observer.unobserve(entry.target);
                    }
                });
            },
            {
                threshold: 0.1,
                rootMargin: '0px 0px -50px 0px'
            }
        );

        sections.forEach((section) => {
            observer.observe(section);
        });
    } else if (page) {
        const sections = page.querySelectorAll('.reveal-section');
        sections.forEach((sec) => sec.classList.add('is-visible'));
    }
});
