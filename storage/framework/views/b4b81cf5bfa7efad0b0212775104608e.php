<script>
    /**
 * Testimonials — infinite auto-playing carousel.
 *
 * Strategy: clone the first N cards and append them to the end of the track.
 * We animate with a CSS transition one card-width at a time. When the
 * transition lands on the cloned set, we snap back to the real first card
 * with the transition disabled for one frame, so the loop never shows a
 * blank gap or a visible jump.
 */
(function () {
    'use strict';

    function initTestimonialsCarousel(track) {
        const originalCards = Array.from(track.children);
        const cardCount = originalCards.length;
        if (cardCount === 0) return;
        const dotsContainer = document.getElementById('testimonialsDots');
        const intervalMs = parseInt(track.dataset.autoplayInterval, 10) || 4000;

        function getVisibleCount() {
            const width = window.innerWidth;
            if (width <= 640) return 1;
            if (width <= 1024) return 2;
            return 3;
        }

        let visibleCount = getVisibleCount();
        let totalPages = Math.ceil(cardCount / visibleCount);
        let currentPage = 0;
        let cardWidth = 0;
        let gap = 0;
        let dots = [];

        function buildDots() {
            if (!dotsContainer) return;
            dotsContainer.innerHTML = '';
            dots = [];
            totalPages = Math.ceil(cardCount / visibleCount);
            if (totalPages <= 1) return; // No dots needed if only 1 page
            for (let i = 0; i < totalPages; i++) {
                const btn = document.createElement('button');
                btn.className = 'testimonials__dot' + (i === currentPage ? ' is-active' : '');
                btn.setAttribute('aria-label', 'Go to page ' + (i + 1));
                btn.addEventListener('click', () => {
                    currentPage = i;
                    goToPage(currentPage, true);
                    play(); // Reset interval
                });
                dotsContainer.appendChild(btn);
                dots.push(btn);
            }
        }

        function updateDots() {
            dots.forEach((dot, i) => {
                if (i === currentPage) {
                    dot.classList.add('is-active');
                } else {
                    dot.classList.remove('is-active');
                }
            });
        }

        function measure() {
            const style = window.getComputedStyle(track);
            gap = parseFloat(style.columnGap || style.gap || '0');
            const firstCard = track.children[0];
            cardWidth = firstCard ? firstCard.getBoundingClientRect().width : 0;
        }

        function goToPage(page, animate) {
            currentPage = page;
            if (currentPage >= totalPages) currentPage = 0;
            if (currentPage < 0) currentPage = totalPages - 1;

            let targetIndex = currentPage * visibleCount;
            // If the last page doesn't have enough cards to fill the view, align to the end
            if (targetIndex + visibleCount > cardCount) {
                targetIndex = Math.max(0, cardCount - visibleCount);
            }

            track.style.transition = animate ? 'transform 0.6s cubic-bezier(0.65, 0, 0.35, 1)' : 'none';
            track.style.transform = 'translateX(-' + (targetIndex * (cardWidth + gap)) + 'px)';
            updateDots();
        }

        function step() {
            currentPage += 1;
            if (currentPage >= totalPages) {
                currentPage = 0;
            }
            goToPage(currentPage, true);
        }

        let timer = null;
        function play() {
            stop();
            if (totalPages > 1) {
                timer = window.setInterval(step, intervalMs);
            }
        }
        function stop() {
            if (timer) {
                window.clearInterval(timer);
                timer = null;
            }
        }

        track.addEventListener('mouseenter', stop);
        track.addEventListener('mouseleave', play);
        track.addEventListener('focusin', stop);
        track.addEventListener('focusout', play);

        let resizeTimeout = null;
        window.addEventListener('resize', () => {
            window.clearTimeout(resizeTimeout);
            resizeTimeout = window.setTimeout(() => {
                const newVisibleCount = getVisibleCount();
                if (newVisibleCount !== visibleCount) {
                    visibleCount = newVisibleCount;
                    currentPage = 0; // Reset to first page
                    buildDots(); // Rebuild dots if visible count changes
                }
                measure();
                goToPage(currentPage, false);
            }, 150);
        });

        measure();
        buildDots();
        goToPage(0, false);
        play();

        if ('IntersectionObserver' in window) {
            const observer = new IntersectionObserver((entries) => {
                entries.forEach((entry) => {
                    if (entry.isIntersecting) {
                        play();
                    } else {
                        stop();
                    }
                });
            }, { threshold: 0.1 });
            observer.observe(track);
        }
    }

    function init() {
        const track = document.getElementById('testimonialsTrack');
        if (track) initTestimonialsCarousel(track);
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', init);
    } else {
        init();
    }
})();
