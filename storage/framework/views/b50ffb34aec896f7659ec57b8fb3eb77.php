<script>
document.addEventListener('DOMContentLoaded', function() {
    const faqItems = document.querySelectorAll('.faq-item');
    
    faqItems.forEach(item => {
        const header = item.querySelector('.faq-item__header');
        
        header.addEventListener('click', () => {
            const isActive = item.classList.contains('active');
            
            // Close all items
            faqItems.forEach(faq => {
                faq.classList.remove('active');
                faq.querySelector('.faq-item__content').style.display = 'none';
            });
            
            // Open clicked item if it wasn't already active
            if (!isActive) {
                item.classList.add('active');
                item.querySelector('.faq-item__content').style.display = 'block';
            }
        });
    });
});

/* ===================== FADE UP ENTRANCE ANIMATION ===================== */
const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
const page = document.querySelector('.pw-case-studies');

if (page && "IntersectionObserver" in window && !prefersReduced) {
    const sections = page.querySelectorAll('.reveal-section');
    const observer = new IntersectionObserver(
        (entries, observer) => {
            entries.forEach((entry) => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('is-visible');
                    observer.unobserve(entry.target);
                }
            });
        },
        {
            threshold: 0.1,
            rootMargin: '0px 0px -50px 0px'
        }
    );

    sections.forEach((section) => {
        observer.observe(section);
    });
} else if (page) {
    const sections = page.querySelectorAll('.reveal-section');
    sections.forEach((sec) => sec.classList.add('is-visible'));
}
</script>
