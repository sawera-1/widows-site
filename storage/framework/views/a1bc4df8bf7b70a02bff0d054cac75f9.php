/* ===================== PREFERS REDUCED MOTION ===================== */
const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

/* ===================== TIMELINE ANIMATION ===================== */
document.addEventListener("DOMContentLoaded", () => {
    if (typeof gsap !== 'undefined' && typeof ScrollTrigger !== 'undefined' && window.innerWidth > 900) {
        gsap.registerPlugin(ScrollTrigger);
        
        const wrapper = document.querySelector('.timeline-wrapper');
        const container = document.querySelector('.timeline-container');
        const items = document.querySelectorAll('.timeline-item');
        const progressLine = document.querySelector('.timeline-progress');
        
        if (wrapper && container && items.length) {
            // Calculate how far to move the container to see all items
            function getScrollAmount() {
                let containerWidth = container.scrollWidth;
                return -(containerWidth - window.innerWidth + 100); 
            }

            const tween = gsap.to(container, {
                x: getScrollAmount,
                ease: "none"
            });

            const scrollTrigger = ScrollTrigger.create({
                trigger: wrapper,
                start: "top 20%",
                end: () => `+=${getScrollAmount() * -1}`,
                pin: true,
                animation: tween,
                scrub: 1,
                invalidateOnRefresh: true
            });

            // Animate progress line width
            gsap.to(progressLine, {
                width: "100%",
                ease: "none",
                scrollTrigger: {
                    trigger: wrapper,
                    start: "top 20%",
                    end: () => `+=${getScrollAmount() * -1}`,
                    scrub: 1
                }
            });

            // Highlight active items
            items.forEach((item, i) => {
                // Determine when the item enters the viewport center
                // Since container is moving, we can trigger off the container's progress
                // or just use intersection observers with a very small rootMargin
                
                // GSAP approach with container motion:
                ScrollTrigger.create({
                    trigger: item,
                    containerAnimation: tween,
                    start: "left center+=10%",
                    end: "right center-=10%",
                    toggleClass: "is-active",
                });
            });
        }
    }
});

/* ===================== ACCORDION ===================== */
// Only one item open at a time. First item is open by default (is-open class in HTML).
document.querySelectorAll('[data-accordion]').forEach((accordion) => {
    const items = accordion.querySelectorAll('[data-accordion-item]');

    function setPanelHeight(item, open) {
        const panel = item.querySelector('[data-accordion-panel]');
        if (open) {
            panel.style.maxHeight = panel.scrollHeight + 'px';
        } else {
            panel.style.maxHeight = '0px';
        }
    }

    // init: apply correct max-height on load based on is-open class
    items.forEach((item) => {
        setPanelHeight(item, item.classList.contains('is-open'));
    });

    items.forEach((item) => {
        const trigger = item.querySelector('[data-accordion-trigger]');

        trigger.addEventListener('click', () => {
            const alreadyOpen = item.classList.contains('is-open');

            // close all items
            items.forEach((el) => {
                el.classList.remove('is-open');
                setPanelHeight(el, false);
            });

            // open the clicked one only if it wasn't already open
            if (!alreadyOpen) {
                item.classList.add('is-open');
                setPanelHeight(item, true);
            }
        });
    });

    // keep open panel height correct on resize (text reflow changes scrollHeight)
    window.addEventListener('resize', () => {
        items.forEach((item) => {
            if (item.classList.contains('is-open')) {
                setPanelHeight(item, true);
            }
        });
    });
});

/* ===================== COUNTERS ===================== */
// Animates each [data-count] number up from 0 once it scrolls into view.
function animateCounter(el) {
    const target = parseInt(el.getAttribute('data-count'), 10);
    const suffix = el.getAttribute('data-suffix') || '';
    
    if (prefersReduced) {
        el.textContent = target + suffix;
        return;
    }

    const duration = 1400; // ms
    const startTime = performance.now();

    function tick(now) {
        const progress = Math.min((now - startTime) / duration, 1);
        // ease-out
        const eased = 1 - Math.pow(1 - progress, 3);
        const value = Math.round(eased * target);
        el.textContent = value + suffix;

        if (progress < 1) {
            requestAnimationFrame(tick);
        } else {
            el.textContent = target + suffix;
        }
    }

    requestAnimationFrame(tick);
}

const counterEls = document.querySelectorAll('[data-count]');

if (counterEls.length) {
    const observer = new IntersectionObserver((entries, obs) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                animateCounter(entry.target);
                obs.unobserve(entry.target);
            }
        });
    }, { threshold: 0.4 });

    counterEls.forEach((el) => observer.observe(el));
}

/* ===================== FADE UP ENTRANCE ANIMATION ===================== */
const page = document.querySelector('.pw-about');
